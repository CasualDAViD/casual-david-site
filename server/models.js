'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { licenseByName, DEFAULT_LICENSE } = require('./catalog');

const SOCIAL_KEYS = [
  'youtube', 'youtubeHandle', 'tiktok', 'tiktokHandle', 'discord',
  'modrinth', 'curseforge', 'personalDiscord', 'email', 'donate'
];
// Keys that hold a link (validated as http/https) versus plain text.
const SOCIAL_URL_KEYS = new Set(['youtube', 'tiktok', 'discord', 'modrinth', 'curseforge', 'personalDiscord', 'donate']);

function newModId() {
  return 'mod-' + crypto.randomBytes(8).toString('hex');
}

function newOrderReference() {
  return 'CD_' + crypto.randomBytes(12).toString('hex');
}

function createModels(db, config) {
  const uploadsDir = path.join(config.dataDir, 'uploads');       // public images
  const filesDir = path.join(config.dataDir, 'private-files');   // paid downloads
  const tmpDir = path.join(config.dataDir, 'tmp');
  for (const dir of [uploadsDir, filesDir, tmpDir]) fs.mkdirSync(dir, { recursive: true });

  const q = {
    mods: db.prepare('SELECT * FROM mods WHERE deleted_at IS NULL ORDER BY created_at DESC, rowid DESC'),
    mod: db.prepare('SELECT * FROM mods WHERE id = ?'),
    shots: db.prepare('SELECT * FROM mod_screenshots WHERE mod_id = ? ORDER BY position, id'),
    sales: db.prepare("SELECT COUNT(*) AS n FROM orders WHERE mod_id = ? AND status = 'paid'"),
    setting: db.prepare('SELECT value FROM settings WHERE key = ?'),
    putSetting: db.prepare('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value')
  };

  const imageUrl = (file) => (file ? `/uploads/${file}` : null);

  function parseJson(text, fallback) {
    try {
      const v = JSON.parse(text);
      return Array.isArray(v) ? v : fallback;
    } catch {
      return fallback;
    }
  }

  // `detail` adds the long description (the shop list does not need it).
  function serializeMod(row, { admin = false, detail = true } = {}) {
    const screenshots = q.shots.all(row.id);
    const license = licenseByName(row.license) || licenseByName(DEFAULT_LICENSE);
    const out = {
      id: row.id,
      name: row.name,
      summary: row.summary,
      class: row.class_name,
      mainCategory: row.main_category,
      categories: parseJson(row.extra_categories, []),
      license: { name: license.name, url: license.url },
      links: parseJson(row.links, []),
      price: row.price_cents / 100,
      icon: imageUrl(row.icon_file),
      screenshots: screenshots.map((s) => imageUrl(s.file)),
      available: Boolean(row.file_stored)
    };
    if (detail || admin) out.description = row.description;
    if (admin) {
      out.unlisted = Boolean(row.unlisted);
      out.screenshotIds = screenshots.map((s) => s.id);
      out.fileName = row.file_name;
      out.fileSize = row.file_size;
      out.sales = q.sales.get(row.id).n;
    }
    return out;
  }

  // The public shop hides unlisted projects; they still open by direct link.
  function listMods({ admin = false } = {}) {
    return q.mods.all()
      .filter((r) => admin || !r.unlisted)
      .map((r) => serializeMod(r, { admin, detail: admin }));
  }

  function getMod(id, opts) {
    const row = typeof id === 'string' ? q.mod.get(id) : null;
    return row && !row.deleted_at ? serializeMod(row, opts) : null;
  }

  // Raw row, including soft-deleted mods (buyers keep access to what they paid for).
  const getModRow = (id) => (typeof id === 'string' ? q.mod.get(id) || null : null);

  function getSocials() {
    const row = q.setting.get('socials');
    if (!row) return {};
    try {
      const data = JSON.parse(row.value);
      return data && typeof data === 'object' ? data : {};
    } catch {
      return {};
    }
  }

  function saveSocials(data) {
    const clean = {};
    for (const key of SOCIAL_KEYS) if (data[key]) clean[key] = data[key];
    q.putSetting.run('socials', JSON.stringify(clean));
    return clean;
  }

  function removeFile(dir, name) {
    if (!name) return;
    // Names are generated by us, but never trust a path read from storage.
    const target = path.join(dir, path.basename(name));
    try { fs.rmSync(target, { force: true }); } catch (err) { console.error('[files] could not delete', target, err.message); }
  }

  return {
    uploadsDir,
    filesDir,
    tmpDir,
    listMods,
    getMod,
    getModRow,
    serializeMod,
    getSocials,
    saveSocials,
    removeImage: (name) => removeFile(uploadsDir, name),
    removePrivateFile: (name) => removeFile(filesDir, name),
    removeTmp: (name) => removeFile(tmpDir, name)
  };
}

module.exports = { createModels, newModId, newOrderReference, SOCIAL_KEYS, SOCIAL_URL_KEYS };
